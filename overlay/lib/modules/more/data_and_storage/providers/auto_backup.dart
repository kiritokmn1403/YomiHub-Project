@riverpod
class BackupFrequencyState extends _$BackupFrequencyState {
  @override
  int build() {
    return settingsRepository.current.backupFrequency ?? 0;
  }

  void set(int value) {
    state = value;
    _setBackupFrequency(value);
  }
}

@riverpod
class BackupFrequencyOptionsState extends _$BackupFrequencyOptionsState {
  @override
  List<int> build() {
    return settingsRepository.current.backupListOptions ??
        [0, 1, 2, 3, 4, 5, 6, 7, 10];
  }

  void set(List<int> values) {
    state = values;
    settingsRepository.update((s) => s.backupListOptions = values);
  }
}

@riverpod
class AutoBackupLocationState extends _$AutoBackupLocationState {
  @override
  (String, String) build() {
    ref.keepAlive();
    _refresh();
    return ("", settingsRepository.current.autoBackupLocation ?? "");
  }

  void set(String location) {
    state = (p.join(_storageProvider!.path, "backup"), location);
    settingsRepository.update((s) => s.autoBackupLocation = location);
  }

  Directory? _storageProvider;

  Future _refresh() async {
    _storageProvider = Platform.isIOS
        ? await StorageProvider().getIosBackupDirectory()
        : await StorageProvider().getDefaultDirectory();
    state = (
      Platform.isIOS
          ? _storageProvider!.path
          : p.join(_storageProvider!.path, "backup"),
      settingsRepository.current.autoBackupLocation ?? "",
    );
  }
}

@riverpod
Future<void> checkAndBackup(Ref ref) async {
  ref.keepAlive();
  final settings = settingsRepository.current;
  final backupFrequency = _duration(settings.backupFrequency);
  if (backupFrequency == null || settings.startDatebackup == null) return;

  final startDatebackup = DateTime.fromMillisecondsSinceEpoch(
    settings.startDatebackup!,
  );
  if (!DateTime.now().isAfter(startDatebackup)) return;
  _setBackupFrequency(settings.backupFrequency!);
  final storageProvider = StorageProvider();
  final backupLocation = ref.read(autoBackupLocationStateProvider).$2;
  Directory? backupDirectory;
  if (Platform.isIOS) {
    backupDirectory = await (storageProvider.getIosBackupDirectory());
  } else {
    final defaultDirectory = await storageProvider.getDefaultDirectory();
    // 0.5.3 (open item of 0.5.2): settings restored from an Android backup
    // carried "/storage/3730-6132/Backup & Sync/..." to Windows, where the
    // auto-backup then created a "\storage\..." folder on the current drive.
    // A location that does not belong to this platform falls back to the
    // default folder (and is logged once) instead of being created.
    final usable = backupLocation.isNotEmpty &&
        _isUsableBackupLocation(backupLocation);
    if (backupLocation.isNotEmpty && !usable) {
      AppLogger.logOnce(
        'autobackup-foreign-path:$backupLocation',
        '[Sao lưu] Vị trí tự sao lưu "$backupLocation" không dùng được trên '
        'thiết bị này (đường dẫn của nền tảng khác hoặc thẻ nhớ đã tháo) – '
        'dùng thư mục mặc định.',
        logLevel: LogLevel.warning,
      );
    }
    backupDirectory = Directory(
      usable ? backupLocation : p.join(defaultDirectory!.path, "backup"),
    );
  }
  final dir = automaticBackupDirectory(backupDirectory!.path);
  if (dir == null) return;
  await storageProvider.createDirectorySafely(dir.path);
  await ref.read(doBackUpProvider(
    list: ref.read(backupFrequencyOptionsStateProvider),
    path: dir.path,
    context: null,
  ).future);
  await pruneOldBackups(dir.path);
}

Directory? automaticBackupDirectory(String location) {
  if (location.trim().isEmpty || !_isUsableBackupLocation(location)) return null;
  final base = p.normalize(location);
  return Directory(p.basename(base) == 'autobackup' ? base : p.join(base, 'autobackup'));
}

// Matches the timestamp generated by writeMangayomiBackupZip.
final _automaticBackupName = RegExp(
  r'^yomihub_\d{4}-\d{2}-\d{2}_\d{2}_\d{2}_\d{2}\.(?:\d{3}|\d{6})\.backup$',
);

Future<void> pruneOldBackups(String backupDirPath, {int? maxRetentionCount}) async {
  final limit = maxRetentionCount ?? YomiPrefs.get<int>('backupMaxCount', 0);
  if (limit <= 0 || !p.isAbsolute(backupDirPath) ||
      p.basename(p.normalize(backupDirPath)) != 'autobackup') {
    return;
  }
  final dir = Directory(backupDirPath);
  try {
    if (await FileSystemEntity.type(dir.path, followLinks: false) != FileSystemEntityType.directory) return;
    final files = await dir.list(followLinks: false).where((entry) =>
        entry is File && _automaticBackupName.hasMatch(p.basename(entry.path))).toList();
    files.sort((a, b) => b.path.compareTo(a.path));
    for (final file in files.skip(limit)) {
      final name = p.basename(file.path);
      try {
        await file.delete();
        AppLogger.log('[Sao lưu] Đã xóa bản tự động: $name', always: true);
      } catch (e) {
        AppLogger.log('[Sao lưu] Không xóa được $name: $e', logLevel: LogLevel.error);
      }
    }
  } catch (e) {
    AppLogger.log('[Sao lưu] Không thể liệt kê thư mục tự sao lưu: $e', logLevel: LogLevel.error);
  }
}

Duration? _duration(int? backupFrequency) {
  return switch (backupFrequency) {
    1 => const Duration(hours: 6),
    2 => const Duration(hours: 12),
    3 => const Duration(days: 1),
    4 => const Duration(days: 2),
    5 => const Duration(days: 7),
    _ => null,
  };
}

void _setBackupFrequency(int value) {
  final duration = _duration(value);
  final now = DateTime.now();
  final startDate = duration != null ? now.add(duration) : null;
  settingsRepository.update(
    (s) => s
      ..backupFrequency = value
      ..startDatebackup = startDate?.millisecondsSinceEpoch,
  );
}

/// 0.5.3: true when [location] is a path of the current platform.
/// Windows needs a drive (C:\) or UNC (\\server) path; Android, Linux
/// and macOS need an absolute POSIX path, and Android paths are not usable
/// on desktop systems.
bool _isUsableBackupLocation(String location) {
  if (Platform.isWindows) {
    return RegExp(r'^[a-zA-Z]:[\\/]').hasMatch(location) ||
        location.startsWith(r'\\');
  }
  if (!location.startsWith('/')) return false;
  // 0.5.3 (Note 9): a folder on an SD card that was removed or replaced
  // (/storage/7563-670C gone) is not usable either - fall back to default.
  if (Platform.isAndroid) {
    final vol = RegExp(r'^/storage/([^/]+)').firstMatch(location)?.group(1);
    if (vol != null &&
        vol != 'emulated' &&
        vol != 'self' &&
        !Directory('/storage/$vol').existsSync()) {
      return false;
    }
  }
  if (!Platform.isAndroid &&
      (location.startsWith('/storage/') || location.startsWith('/sdcard'))) {
    return false;
  }
  return true;
}
